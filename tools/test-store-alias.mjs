#!/usr/bin/env node
// Один магазин — одно имя.
//
// «Лемана» и «Лемана ПРО» — одна и та же сеть: вывеску сменили, а в базе
// остались оба написания. Пока они разные, лист закупки делится надвое, и
// человек едет в один магазин по двум спискам, каждый раз думая, не забыл ли
// он второй. Поэтому имя приводится к нынешней вывеске при ЛЮБОМ вводе:
// руками, по ссылке и из встроенных справочников.
import { boot, reporter } from './harness/panel-vm.js'

const t = reporter()
const p = boot({})

// ── Приведение имени ────────────────────────────────────────────────────────
{
  t.section('Прежние вывески сводятся к нынешней')
  t.ok('«Лемана» → «Лемана ПРО»', p.q('normStore("Лемана")') === 'Лемана ПРО')
  t.ok('регистр не мешает', p.q('normStore("лемана")') === 'Лемана ПРО')
  t.ok('лишние пробелы не мешают', p.q('normStore("  Лемана  ")') === 'Лемана ПРО')
  t.ok('двойной пробел внутри схлопывается', p.q('normStore("Лемана  ПРО")') === 'Лемана ПРО')
  t.ok('старое «Леруа Мерлен» — та же сеть', p.q('normStore("Леруа Мерлен")') === 'Лемана ПРО')
  t.ok('уже верное имя не портится', p.q('normStore("Лемана ПРО")') === 'Лемана ПРО')

  // Чужие магазины не трогаем: нормализация — про одну сеть, а не про то,
  // чтобы причёсывать всё подряд.
  t.ok('Озон остаётся Озоном', p.q('normStore("Озон")') === 'Озон')
  t.ok('незнакомое имя проходит как есть', p.q('normStore("Славянский мир")') === 'Славянский мир')
  t.ok('пусто остаётся пустым', p.q('normStore("")') === '')
  t.ok('без значения не падает', p.q('normStore(null)') === '')
}

// ── Магазин по ссылке ───────────────────────────────────────────────────────
// Самая частая дверь: цену приносит обход магазинов или вставленная ссылка.
{
  t.section('Ссылка заводит магазин под нынешним именем')
  t.ok('lemanapro.ru → «Лемана ПРО»',
    p.q('shopFromUrl("https://lemanapro.ru/product/mufta-politek-20-mm-13563101/")') === 'Лемана ПРО',
    p.q('shopFromUrl("https://lemanapro.ru/product/mufta-politek-20-mm-13563101/")'))
  // Старый домен сети ведёт в тот же магазин — значит и имя должно быть одно.
  t.ok('leroymerlin.ru → «Лемана ПРО»',
    p.q('shopFromUrl("https://leroymerlin.ru/product/x-123/")') === 'Лемана ПРО')
  t.ok('чужой магазин не переименован',
    p.q('shopFromUrl("https://www.ozon.ru/product/x-123/")') === 'Озон')
}

// ── Цвет бейджа ─────────────────────────────────────────────────────────────
// Бейдж магазина узнают по цвету раньше, чем читают текст. Если у нового имени
// цвета нет, половина строк станет серой и перестанет читаться с одного взгляда.
{
  t.section('Бейдж не теряет цвет')
  t.ok('у «Лемана ПРО» есть свой цвет', p.q('SC["Лемана ПРО"]') === '#e30613')
  t.ok('прежнее имя тоже раскрашено', p.q('SC["Лемана"]') === '#e30613',
    'снимок из старой вкладки нарисуется серым')
}

// ── Встроенные справочники ──────────────────────────────────────────────────
// Сиды — это то, откуда работы и материалы попадают в новый дом. Оставить в них
// старое имя значит заводить расхождение заново с каждым домом.
{
  t.section('Встроенные справочники — под новым именем')
  const stores = (arr) => new Set(arr)
  // boot() не подменял состояние — значит это ровно встроенные справочники.
  const dbw = p.q('(dbWorks||[]).reduce(function(a,w){return a.concat((w.mats||[]).map(function(m){return m.store||"";}));},[])')
  const dbm = p.q('(expProducts||[]).map(function(m){return m.store||"";})')
  t.ok('в работах нет старого имени', !stores(dbw).has('Лемана'), JSON.stringify([...stores(dbw)]))
  t.ok('и новое там есть', stores(dbw).has('Лемана ПРО'))
  t.ok('в материалах нет старого имени', !stores(dbm).has('Лемана'), JSON.stringify([...stores(dbm)]))
}

t.done()
