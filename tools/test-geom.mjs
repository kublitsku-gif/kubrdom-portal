#!/usr/bin/env node
// Геометрия планировки (src/geom.js).
//
// Здесь считаются площади, по которым выставляют счёт, поэтому сторожим не «код
// работает», а арифметику: сумма площадей помещений равна площади пола, периметр
// Г-образной комнаты больше периметра прямоугольника той же площади, а стена, не
// дошедшая до конца, помещений НЕ делит — через проход комната остаётся одной.
import { regions, regionAt, grid } from '../src/geom.js'

let failed = 0
const ok = (name, cond, extra) => {
  if (cond) return console.log('  ✓ ' + name)
  failed++
  console.log('  ✗ ' + name + (extra ? '\n      ' + extra : ''))
}
const m2 = (mm2) => Math.round(mm2 / 1000 / 1000 * 100) / 100

// Коробка 6000 × 2400 с обшивкой 100: считаем по ЧИСТОВОМУ полю, как модель.
const W = 6000, H = 2400, TH = 100

// ── 1. Пустая коробка ────────────────────────────────────────────────────────
{
  console.log('Пустая коробка')
  const r = regions(W, H, [])
  ok('одно помещение', r.length === 1, String(r.length))
  ok('площадь равна габариту', r[0].area === W * H, m2(r[0].area) + ' м²')
  ok('периметр равен обходу', r[0].perimeter === 2 * (W + H), String(r[0].perimeter))
  ok('оно прямоугольное', r[0].rect === true)
  ok('подпись внутри', regionAt(r, r[0].label.x, r[0].label.y) === r[0])
}

// ── 2. Перегородка от стены до стены ─────────────────────────────────────────
{
  console.log('Стена во всю ширину')
  const r = regions(W, H, [{ x: 2000, y: 0, w: TH, h: H }])
  ok('помещений два', r.length === 2, String(r.length))
  const areas = r.map((x) => x.area).sort((a, b) => a - b)
  ok('площади — по обе стороны стены',
    areas[0] === 2000 * H && areas[1] === (W - 2000 - TH) * H, areas.map(m2).join(' / '))
  ok('сумма площадей + стена = пол', areas[0] + areas[1] + TH * H === W * H)
  ok('обе прямоугольные', r.every((x) => x.rect))
}

// ── 3. Стена НЕ во всю ширину: помещение остаётся одним ──────────────────────
// Это и есть «нестандартное помещение»: стена-огрызок делает комнату Г-образной,
// а не двумя комнатами. Раньше такую стену модель поставить не могла вовсе.
{
  console.log('Стена-огрызок')
  const stub = { x: 2000, y: 0, w: TH, h: 1400 }      // от верхней стены, не до низа
  const r = regions(W, H, [stub])
  ok('помещение по-прежнему одно', r.length === 1, String(r.length))
  ok('площадь — за вычетом стены', r[0].area === W * H - TH * 1400, m2(r[0].area) + ' м²')
  ok('и оно уже не прямоугольное', r[0].rect === false)
  // Периметр вырос на обе стороны огрызка: его торец добавился, но ровно столько же
  // наружной стены он собой закрыл. Именно эти метры штукатурят — по ним считается
  // отделка стен, и у Г-образной комнаты их больше, чем у прямоугольной.
  ok('периметр вырос на обе стороны огрызка',
    r[0].perimeter === 2 * (W + H) + 2 * 1400, String(r[0].perimeter))
  ok('подпись попала внутрь комнаты', regionAt(r, r[0].label.x, r[0].label.y) === r[0])
}

// ── 4. Кладовка в углу: две стены-огрызка ────────────────────────────────────
{
  console.log('Кладовка из двух огрызков')
  // Кладовку в углу замыкают ТРИ стены: две поперёк и одна вдоль. С двумя она
  // остаётся открытой сбоку — и это не придирка теста, а то, как считается площадь:
  // открытая ниша принадлежит комнате, закрытая кладовка — сама себе.
  const walls = [
    { x: 2000, y: 0, w: TH, h: 1200 },                  // левая стенка кладовки
    { x: 3400, y: 0, w: TH, h: 1200 },                  // правая
    { x: 2000, y: 1100, w: 1500, h: TH },               // вдоль, замыкает снизу
  ]
  const r = regions(W, H, walls)
  ok('комнат две: кладовка и Г-образная кухня', r.length === 2, String(r.length))
  const small = r.reduce((a, b) => (a.area < b.area ? a : b))
  const big = r.reduce((a, b) => (a.area > b.area ? a : b))
  ok('кладовка прямоугольная', small.rect === true)
  ok('кладовка 1300 × 1100', small.area === 1300 * 1100, m2(small.area) + ' м²')
  ok('кухня — не прямоугольник', big.rect === false)
  // Стены пересекаются, поэтому их площадь считаем объединением, а не суммой.
  const wallArea = TH * 1200 + TH * 1200 + 1500 * TH - TH * TH * 2
  ok('пол = площади помещений плюс стены',
    small.area + big.area + wallArea === W * H,
    (small.area + big.area) + ' + ' + wallArea + ' против ' + W * H)

  // Уберём замыкающую стенку — кладовка становится нишей той же комнаты.
  const open = regions(W, H, walls.slice(0, 2).concat([{ x: 2000, y: 1100, w: 700, h: TH }]))
  ok('незамкнутая кладовка — часть комнаты', open.length === 1, String(open.length))
}

// ── 5. Замкнутая выгородка внутри плана ──────────────────────────────────────
// Шахта или котельная посреди комнаты: снаружи комната, внутри — своё помещение.
{
  console.log('Замкнутая выгородка')
  const box = [
    { x: 2000, y: 800, w: 1200, h: TH },
    { x: 2000, y: 800 + 900, w: 1200, h: TH },
    { x: 2000, y: 800, w: TH, h: 900 + TH },
    { x: 2000 + 1200 - TH, y: 800, w: TH, h: 900 + TH },
  ]
  const r = regions(W, H, box)
  ok('помещений два', r.length === 2, String(r.length))
  const inner = r.reduce((a, b) => (a.area < b.area ? a : b))
  ok('внутреннее помещение отдельное', inner.area === (1200 - TH * 2) * (900 - TH), m2(inner.area) + ' м²')
  ok('и оно не касается наружного',
    regionAt(r, 2000 - 10, 800 + 400) !== inner)
}

// ── 6. Сетка не плодит клетки на пустом месте ────────────────────────────────
{
  console.log('Разрез плана')
  const g = grid(W, H, [{ x: 2000, y: 0, w: TH, h: H }])
  ok('по длине три отметки-полосы', g.nx === 3, String(g.nx))
  ok('по ширине одна', g.ny === 1, String(g.ny))
  ok('клетка стены помечена', g.solid.filter(Boolean).length === 1, String(g.solid.filter(Boolean).length))
}

console.log(failed ? `\n✘ провалено проверок: ${failed}` : '\n✓ все проверки прошли')
process.exit(failed ? 1 : 0)
