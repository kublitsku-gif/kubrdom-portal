import assert from 'node:assert/strict';
import { changeClient, mergeClients, cohortReport, duplicateCandidates, nextAt, activeClient, campaignReport, cleanBriefSuggestion } from '../src/crm-sales.js';
import { chatFeed, todayReminders, dueReminders, salesSummary } from '../src/crm-app.js';
import { boot } from './harness/panel-vm.js';
const now=Date.now(), before=now-10000;
const original={id:'a',name:'Анна',phone:'+79991234567',source:'Сайт',stage:'new',date:new Date(now).toISOString().slice(0,10),createdAt:before,notes:'',avitoKey:'a-chat'};
let c=changeClient(original,{stage:'contract'},'Юрий',now);
let report=cohortReport([c],before-1);
assert.equal(report.funnel.find(x=>x.id==='contract').count,1);
assert.equal(report.funnel.find(x=>x.id==='meeting').count,0,'direct contract jump does not fabricate a meeting');
c=changeClient(c,{stage:'new'},'Юрий',now+1);
assert.equal(cohortReport([c],before-1,now+2).funnel.find(x=>x.id==='contract').count,1,'moving back preserves historical conversion');
c=changeClient(c,{remindAt:now-1,remindNote:'Позвонить'},'Юрий',now);
assert.equal(c.salesFollowupAt,now-1);assert.equal(dueReminders([c],{},now).length,1);
c=changeClient(c,{remindAt:null},'Юрий',now+1);assert.equal(nextAt(c),0);assert.equal(dueReminders([c],{},now+2).length,0);
assert.equal(todayReminders([{...original,salesFollowupAt:now}],now).length,1,'legacy Telegram callback is in Today');
assert.equal(activeClient({...original,salesStatus:'refused'}),false);
assert.equal(salesSummary({'a-chat':{source:'avito',messages:[]}},[{...original,stage:'contract'}],['new','meeting','contract'].map(id=>({id})),now).listings[0].meetings,0);
const second={...original,id:'b',phone:'8 (999) 123-45-67',avitoKey:'b-chat',notes:'Важная заметка',history:[{id:'b-event',at:now,text:'Встреча'}]};
assert.equal(duplicateCandidates(original,[original,second]).length,1);
const [merged,hidden]=mergeClients(original,second,'Юрий',now);
assert.equal(hidden.mergedInto,'a');assert.equal(merged.notes,'Важная заметка');assert.equal(merged.history.length,2);
const feed=chatFeed({'a-chat':{source:'avito',messages:[]},'b-chat':{source:'avito',messages:[]}},[merged,hidden]);
assert.ok(feed.every(f=>f.clientId==='a'));
assert.equal(cohortReport([merged,hidden],before-1).count,1);
assert.equal(dueReminders([{...hidden,remindAt:now}],{},now).length,0);
const ads=campaignReport([original],[{campaign:'Сайт',date:original.date,amount:5000}],[{crmClientId:'a',status:'closed',amount:200000},{crmClientId:'a',status:'draft',amount:100}],before-86400000);
assert.equal(ads[0].contracts,1);assert.equal(ads[0].revenue,200000);assert.equal(ads[0].cost,5000);
assert.deepEqual(cleanBriefSuggestion({brief:{budget:'100000',ownerId:'evil'},summary:'Запрос'}).brief,{budget:'100000'});
// Real panel rendering and handlers, without network or production records.
const b=boot();b.set({crmClients:[original,second],crmChats:{},users:[{id:'t',name:'Тест',roles:['admin']}],settings:{},contractDocs:[],crmOpenId:'a',crmView:'client'});
const html=b.run('tCRMClient("a")');assert.ok(html.includes('sales-profile')&&html.includes('sales-ai')&&html.includes('sales-proposal'));
b.dom.field('sales-brief-budget','900000');b.dom.field('sales-brief-product','Баня');
await b.run('salesAction("brief","a",{})');assert.equal(b.q('crmClients[0].brief.budget'),'900000');
b.dom.field('sales-event','Созвонились: клиент приедет в пятницу');await b.run('salesAction("event","a",{})');assert.equal(b.q('crmClients[0].history.length'),1);
b.dom.field('sales-kp-title','Баня 6 м');b.dom.field('sales-kp-url','https://example.org/offer.pdf');b.dom.field('sales-kp-amount','1200000');
await b.run('salesAction("proposal","a",{})');assert.equal(b.q('crmClients[0].proposals[0].amount'),1200000);
await b.run('salesAction("merge","a|b",{})');assert.equal(b.q('crmClients[1].mergedInto'),'a');
assert.ok(b.run('tCRMFunnel()').includes('Без следующего действия'));
assert.ok(b.run('tCRMSummary()').includes('Отдача рекламы'));
console.log('✓ CRM sales: history, cohorts, tasks, ownership UI, brief, proposals, merges, ads, AI validation and real panel handlers');
