// Открыть проект — так, как это делает человек: «+ Проект» → имя → «Создать».
//
// Экран чертежа и экран сметы живут в ПРОЕКТЕ: опытный раздел «Спецификация 2»
// закрыт 16.09.2026, и второй двери в эти экраны больше нет. Наборы, которым
// нужен живой лист (цены магазинов, мастер цен, часы, редактор модели, смета),
// заводили его тремя строками через кнопку раздела; теперь тот же путь один на
// всех и лежит здесь — иначе при следующей правке формы создания его пришлось бы
// чинить в шести файлах.
//
// Заготовка та же, что была у раздела (`MODEL_PRESETS[0]`), поэтому числа в
// проверках не поехали: это тот же дом, просто заведённый с другого экрана.
export function openProject(p, name) {
  p.run('tab="projects";projOpenId=null;tProjects();')
  const add = p.dom.node({ a: 'proj-new' })
  p.run('bind();')
  add.onclick()
  p.dom.field('proj-n-name', name || 'Дом')
  p.dom.field('proj-n-client', '')
  p.run('tProjects();')
  const go = p.dom.node({ a: 'proj-create' })
  p.run('bind();')
  go.onclick()
  // Редактор закрываем, этапы сметы разворачиваем: проверкам нужны сами строки,
  // а свёрнутость этапов сторожат свои наборы.
  p.run('modelFull=false;stageOpen={0:1,1:1,2:1,3:1,4:1,5:1,6:1};')
  return p.q('projOpenId')
}

// Полоса «🧾 Состав» — смета по чертежу.
export function estHtml(p) {
  return p.run('projBand="parts";tProjects()')
}

// Полоса «📐 Чертёж» — схема, узлы, площади.
export function planHtml(p) {
  return p.run('projBand="plan";tProjects()')
}

