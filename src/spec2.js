// ─── СПЕЦИФИКАЦИЯ 2 — ЭКСПЕРИМЕНТАЛЬНЫЙ РАЗДЕЛ ───────────────────────────────
// Второй, опытный заход на ту же продажу. Отличается тремя вещами, и только ими:
//
//  1. СВОИ ДАННЫЕ. Листы лежат в разделе снимка `specSheets2`, а не рядом с боевыми.
//     Эксперимент, который пишет в проданные спецификации, — это не эксперимент,
//     а авария: по ним уже заведены договора, объекты и транши.
//  2. ДОМ НАЧИНАЕТСЯ С МОДЕЛИ. Здесь не «выбери планировку, а потом, может быть,
//     собери модель», а сразу коробка контейнера с перегородками и проёмами.
//     Поэтому и «готово» тут считается иначе — см. issues2.
//  3. МЕСТО ДЛЯ РАСХОЖДЕНИЯ. Всё, чем расчёт «Спецификации 2» будет отличаться от
//     боевого, живёт в этом файле — не в панели.
//
// Чего здесь намеренно НЕТ — своей копии денег. Цену считает боевой модуль
// (`src/spec.js`): та же сумма уходит в печатную форму клиенту, в договор и в
// объект. Разойдись формулы — клиент получит одну цену на руки и другую в
// договоре, а найдётся это в лучшем случае на приёмке этапа. Когда для опыта
// понадобится СВОЯ цена, её место — здесь, в totals2, и это будет осознанная
// развилка, а не побочный эффект правки панели.

import { sheetTotals, sheetIssues } from "./spec.js";

// Деньги — общие с боевым разделом. См. заголовок: это не заглушка, а решение.
export function totals2(sheet, estimates, products) {
  return sheetTotals(sheet, estimates, products);
}

// А вот что считать готовым — уже своё. В боевом разделе спецификация без модели
// нормальна (размеры приходят из планировки), здесь же она пустой лист: считать
// нечего, пока не собрана коробка. Про «нет помещений» боевой список тогда молчит —
// два сообщения об одном и том же продавец читает как шум.
export function issues2(sheet, estimates, products) {
  const own = [];
  const model = (sheet && sheet.model) || null;
  if (!model) own.push("Не собрана модель контейнера — в этом разделе дом начинается с неё");
  else if (((model.rooms || []).length) < 2) own.push("В модели одно помещение — перегородок ещё нет");
  const rest = sheetIssues(sheet, estimates, products).filter(function (x) {
    return own.length ? String(x).indexOf("Нет помещений") !== 0 : true;
  });
  return own.concat(rest);
}
