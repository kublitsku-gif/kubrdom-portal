// Дата как строка YYYY-MM-DD — без ухода в UTC.
//
// Грабли, на которые наступали: дату в панели строят ЛОКАЛЬНЫМ календарём —
// `new Date("2026-09-19T00:00:00")` (локальная полночь), потом `setDate(+1)` по
// рабочим дням. А обратно в строку клали через `toISOString().slice(0,10)`, и
// это переводит в UTC: в Москве (UTC+3) локальная полночь 11.12.2026 — это
// 10.12.2026T21:00Z, и в договор уходил дедлайн на день раньше.
//
// Поэтому: собрал дату локальным календарём — и назад разбирай локальным.
// `toISOString()` оставляем только там, где нужна настоящая метка времени UTC.
//
// Осознанное исключение — «день по Москве» (`Date.now() + 3ч` в admin.js и
// `mskToday()` в src/reminders.js): там дело не в поясе браузера, а в том, что
// рабочий день у компании считается по МСК, и панель обязана совпасть с ботом.

export function isoLocal(d) {
  if (!(d instanceof Date) || isNaN(d.getTime())) return "";
  const p = (n) => String(n).padStart(2, "0");
  return d.getFullYear() + "-" + p(d.getMonth() + 1) + "-" + p(d.getDate());
}

// Сегодня по календарю того, кто смотрит. Раньше здесь был UTC, и после 21:00
// по Москве панель весь вечер подставляла вчерашнее число.
export function todayISO() { return isoLocal(new Date()); }
